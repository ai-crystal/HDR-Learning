# ---------------- 视锥基函数（Smith–Pokorny 线性变换，源自标准观察者） ----------------
# l̄ + m̄ = ȳ，故 Y = L + M，与"Y 即亮度"一致。
_L = 0.15514 * XBAR + 0.54312 * YBAR - 0.03286 * ZBAR
_M = -0.15514 * XBAR + 0.45684 * YBAR + 0.03286 * ZBAR
_S = 0.01608 * ZBAR
L_CONE = np.clip(_L, 0.0, None)
M_CONE = np.clip(_M, 0.0, None)
S_CONE = np.clip(_S, 0.0, None)


def peak_wavelength(curve):
    """返回曲线的峰值波长与峰值。"""
    i = int(np.argmax(curve))
    return LAM[i], curve[i]


def xyz_to_linear_srgb(X, Y, Z):
    """CIE XYZ -> 线性 sRGB（D65）。输入可为数组。"""
    X = np.asarray(X, dtype=float)
    Y = np.asarray(Y, dtype=float)
    Z = np.asarray(Z, dtype=float)
    r = 3.2406 * X - 1.5372 * Y - 0.4986 * Z
    g = -0.9689 * X + 1.8758 * Y + 0.0415 * Z
    b = 0.0557 * X - 0.2040 * Y + 1.0570 * Z
    return np.stack([r, g, b], axis=-1)


def xyz_to_srgb01(X, Y, Z):
    """CIE XYZ -> sRGB 码值 0..1（不做色域裁剪外的伽马近似）。"""
    lin = np.clip(xyz_to_linear_srgb(X, Y, Z), 0.0, 1.0)
    a = 0.0031308
    out = np.where(lin <= a, 12.92 * lin, 1.055 * np.power(lin, 1.0 / 2.4) - 0.055)
    return np.clip(out, 0.0, 1.0)


def wavelength_to_srgb01(lam, normalized=True):
    """单波长 -> sRGB 颜色（RGB 归一化后提亮，用于画光谱带）。"""
    lam = np.atleast_1d(np.asarray(lam, dtype=float))
    Xi = np.interp(lam, LAM, XBAR)
    Yi = np.interp(lam, LAM, YBAR)
    Zi = np.interp(lam, LAM, ZBAR)
    rgb = np.clip(xyz_to_linear_srgb(Xi, Yi, Zi), 0.0, None)
    if normalized:
        m = rgb.max(axis=-1, keepdims=True)
        m[m < 1e-9] = 1.0
        rgb = rgb / m
    a = 0.0031308
    out = np.where(rgb <= a, 12.92 * rgb, 1.055 * np.power(np.clip(rgb, 0, None), 1 / 2.4) - 0.055)
    return np.clip(out, 0, 1)


def xy_to_xyz(x, y, Y=1.0):
    """色度坐标 (x,y) + 亮度 Y -> XYZ。"""
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    X = x * Y / np.maximum(y, 1e-9)
    Z = (1.0 - x - y) * Y / np.maximum(y, 1e-9)
    return X, np.full_like(x, Y), Z


def xy_to_srgb01(x, y, Y=1.0):
    X, Yv, Z = xy_to_xyz(x, y, Y)
    return xyz_to_srgb01(X, Yv, Z)


def spectral_locus(n_dense=2000):
    """返回光谱轨迹的 (x,y) 与对应波长（线性积分插值加密）。"""
    lam = np.linspace(380.0, 780.0, n_dense)
    X = np.interp(lam, LAM, XBAR)
    Y = np.interp(lam, LAM, YBAR)
    Z = np.interp(lam, LAM, ZBAR)
    s = X + Y + Z
    return lam, X / s, Y / s


def horseshoe_outline():
    """马蹄形边界（光谱轨迹 + 紫线闭合），用于填充与内外判定。"""
    lam, x, y = spectral_locus()
    xs = np.concatenate([x, [x[0]]])
    ys = np.concatenate([y, [y[0]]])
    return xs, ys


